/**
 * Seed Demo Users - Creates synthetic accounts for local development
 *
 * These are FAKE, invented people. They exist so a fresh clone can log in
 * without any real member data. Never replace these with real member records.
 *
 * Safety rules:
 *  - Refuses to run when NODE_ENV === "production".
 *  - Never uses a hardcoded password. Either reads DEMO_USER_PASSWORD or
 *    generates a random one and prints it once.
 *
 * Run with: node scripts/seed/seed-demo-users.js
 */

const crypto = require("crypto");
const bcrypt = require("bcryptjs");
const prisma = require("../shared/prisma-client");

const DEMO_USERS = [
  {
    username: "demo-admin",
    email: "demo-admin@example.com",
    displayName: "Ada Demo",
    givenName: "Ada",
    familyName: "Demo",
    gender: "F",
    birthYear: 1985,
    role: "ADMIN",
  },
  {
    username: "demo-user",
    email: "demo-user@example.com",
    displayName: "Bob Example",
    givenName: "Bob",
    familyName: "Example",
    gender: "M",
    birthYear: 1990,
    role: "USER",
  },
  {
    username: "demo-member",
    email: "demo-member@example.com",
    displayName: "Cara Sample",
    givenName: "Cara",
    familyName: "Sample",
    gender: "F",
    birthYear: 1978,
    role: "USER",
  },
];

function resolveDemoPassword() {
  const fromEnv = process.env.DEMO_USER_PASSWORD;
  if (fromEnv && fromEnv.length >= 8) {
    return { password: fromEnv, generated: false };
  }
  return {
    password: `demo-${crypto.randomBytes(9).toString("base64url")}`,
    generated: true,
  };
}

async function seedDemoUsers() {
  console.log("\n👤 Seeding demo (synthetic) users...");

  if (process.env.NODE_ENV === "production") {
    console.warn(
      "⚠️  Skipping demo users: NODE_ENV=production. Demo accounts must never exist in production."
    );
    return { created: 0, updated: 0, skipped: true };
  }

  const { password, generated } = resolveDemoPassword();
  const hashedPassword = await bcrypt.hash(password, 12);

  let created = 0;
  let updated = 0;

  for (const demo of DEMO_USERS) {
    const existing = await prisma.user.findFirst({
      where: {
        OR: [{ username: demo.username }, { email: demo.email }],
      },
      select: { id: true },
    });

    const data = {
      username: demo.username,
      email: demo.email,
      password: hashedPassword,
      passwordChangedAt: new Date(),
      emailVerified: new Date(),
      role: demo.role,
      status: "ACTIVE",
      displayName: demo.displayName,
      givenName: demo.givenName,
      familyName: demo.familyName,
      gender: demo.gender,
      birthYear: demo.birthYear,
      notes: "Synthetic demo account generated by scripts/seed/seed-demo-users.js",
    };

    if (existing) {
      await prisma.user.update({ where: { id: existing.id }, data });
      updated++;
    } else {
      await prisma.user.create({ data });
      created++;
    }
  }

  console.log(`✅ Demo users: ${created} created, ${updated} updated`);
  console.log("   Accounts (all synthetic, @example.com):");
  for (const demo of DEMO_USERS) {
    console.log(`   - ${demo.username} (${demo.role})`);
  }

  if (generated) {
    console.log("\n   🔑 Generated demo password (shown once, not stored in git):");
    console.log(`      ${password}`);
    console.log(
      "   Set DEMO_USER_PASSWORD to choose your own, or run `npm run db:reset-password`."
    );
  } else {
    console.log("\n   🔑 Demo password taken from DEMO_USER_PASSWORD.");
  }

  return { created, updated, skipped: false };
}

module.exports = { seedDemoUsers };

// Allow direct execution: node scripts/seed/seed-demo-users.js
if (require.main === module) {
  seedDemoUsers()
    .catch((error) => {
      console.error(error);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
